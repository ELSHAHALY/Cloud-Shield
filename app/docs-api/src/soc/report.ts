// IR report "live verification view" (plan D17 §7.4): the IrReport field
// names of soar/tools/generate_ir_report.py (minus ai_summary and
// iac_remediation), rendered as JSON or as a Markdown download. The Python
// tool stays authoritative. Every interpolated value is escaped so the
// Markdown can never carry raw HTML.
import { triage } from "./triage";
import { MTTC_TARGET_SECONDS, mttcOf, parseTime, secondsBetween } from "./time";
import { actions, num, str } from "./projection";
import type { EvidenceCheck } from "./evidence";
import type { Row } from "./repository";

export const AUTHORITATIVE = "authoritative report: make ir-report INCIDENT=<id>";
export const GENERATED_BY = "Live verification view generated by docs-api";

export function buildReport(row: Row, checks: EvidenceCheck[], chainOfCustodyOk: boolean | null) {
  const status = String(row.status ?? "UNKNOWN");
  const mttc = mttcOf(row);
  const met = mttc === null ? null : mttc < MTTC_TARGET_SECONDS;
  const verdict = mttc === null ? "not contained: no MTTC is recorded" : `${met ? "met" : "MISSED"}: ${mttc.toFixed(3)} s against the ${MTTC_TARGET_SECONDS} s target`;
  const severity = num(row.severity);
  return {
    incident_id: String(row.incidentId),
    status,
    finding_type: str(row.findingType),
    severity: severity === null ? null : severity,
    resource_type: str(row.resourceType, 64),
    finding_created_at: str(row.findingCreatedAt, 40),
    event_time: str(row.eventTime, 40),
    contained_at: status === "CONTAINED" && parseTime(row.containedAt) !== null ? str(row.containedAt, 40) : null,
    containment_verified: typeof row.containmentVerified === "boolean" ? row.containmentVerified : null,
    mttc_seconds: mttc,
    detection_latency_seconds: secondsBetween(parseTime(row.findingCreatedAt), parseTime(row.eventTime)),
    mttc_target_met: met,
    execution_arn: str(row.executionArn),
    actions: actions(row),
    evidence: checks.map((c) => ({ key: c.key, version_id: c.versionId, recorded_sha256: c.recordedSha256, actual_sha256: c.actualSha256, ok: c.ok, error: c.error })),
    guard_reason: str(row.guardReason),
    failure: str(row.failure),
    executive_summary: { status, mttc_verdict: verdict, ...triage(row.findingType) },
    chain_of_custody_ok: chainOfCustodyOk,
    generated_by: GENERATED_BY,
    authoritative: AUTHORITATIVE.replace("<id>", String(row.incidentId)),
  };
}

export type IrReport = ReturnType<typeof buildReport>;

/** Escape a value for a Markdown table cell or inline code: no HTML, no pipes, no backticks. */
export function md(value: unknown): string {
  if (value === null || value === undefined) return "—";
  return String(value)
    .replace(/&/g, "&amp;")
    .replace(/</g, "&lt;")
    .replace(/>/g, "&gt;")
    .replace(/\|/g, "\\|")
    .replace(/`/g, "'")
    .replace(/[\r\n]+/g, " ");
}

export function toMarkdown(r: IrReport): string {
  const s = r.executive_summary;
  const mttc = r.mttc_seconds !== null ? `${r.mttc_seconds.toFixed(3)} s (${r.mttc_target_met ? "meets" : "MISSES"} the ${MTTC_TARGET_SECONDS} s target)` : "— (not contained: no MTTC is recorded)";
  const lines = [
    `# Incident report: \`${md(r.incident_id)}\``,
    "",
    `> ${GENERATED_BY}; ${md(r.authoritative)}.`,
    "",
    "## Executive summary",
    "",
    `- **Status:** ${md(r.status)}`,
    `- **MTTC:** ${md(s.mttc_verdict)}`,
    `- **Impact:** ${md(s.impact)}`,
    `- **ATT&CK:** ${s.attack_techniques.length ? s.attack_techniques.map(md).join(", ") : "analyst review"} (${md(s.tactic)})`,
    `- **Scenario:** ${md(s.scenario)}`,
    "",
    "**Eradication (human):**",
    "",
    ...s.eradication.map((x) => `- [ ] ${md(x)}`),
    "",
    "**Recovery (human):**",
    "",
    ...s.recovery.map((x) => `- [ ] ${md(x)}`),
    ...(s.references.length ? ["", "References: " + s.references.map((x) => `\`${md(x)}\``).join(", ")] : []),
    "",
    "## Incident record",
    "",
    "| Field | Value |",
    "|---|---|",
    `| Status | **${md(r.status)}** |`,
    `| Finding type | \`${md(r.finding_type)}\` |`,
    `| Severity | ${md(r.severity)} |`,
    `| Resource type | ${md(r.resource_type)} |`,
    `| GuardDuty createdAt | ${md(r.finding_created_at)} |`,
    `| EventBridge time (MTTC start) | ${md(r.event_time)} |`,
    `| Contained at (MTTC stop) | ${md(r.contained_at)} |`,
    `| MTTC | ${md(mttc)} |`,
    `| Detection latency (createdAt -> event) | ${md(r.detection_latency_seconds)} s |`,
    `| Playbook verified containment | ${md(r.containment_verified)} |`,
    `| Step Functions execution | \`${md(r.execution_arn)}\` |`,
  ];
  if (r.guard_reason) lines.push(`| Safety guard decision | \`${md(r.guard_reason)}\` |`);
  if (r.failure) lines.push(`| Failure | \`${md(r.failure)}\` |`);
  lines.push("", "## Containment actions", "");
  if (r.actions.length) {
    lines.push("| Time | Playbook | Step | Details |", "|---|---|---|---|");
    for (const a of r.actions) lines.push(`| ${md(a.at)} | ${md(a.playbook)} | ${md(a.step)} | \`${md(a.details ?? "{}")}\` |`);
  } else {
    lines.push("No playbook actions recorded.");
  }
  lines.push("", "## Evidence (SHA-256 recomputed from S3)", "");
  if (r.evidence.length) {
    lines.push("| Object | Recorded | Recomputed | Match |", "|---|---|---|---|");
    for (const e of r.evidence) lines.push(`| \`${md(e.key)}\` | \`${md(e.recorded_sha256)}\` | \`${md(e.actual_sha256)}\` | ${e.ok ? "✓" : `✗ ${md(e.error ?? "mismatch")}`} |`);
    const verdict = r.chain_of_custody_ok === true ? "intact" : r.chain_of_custody_ok === false ? "**BROKEN**" : "not fully verified (more than 20 objects: run the authoritative tool)";
    lines.push("", `Chain of custody: ${verdict}.`);
  } else {
    lines.push("No evidence recorded for this incident.");
  }
  lines.push("", "IaC remediation and the AI summary are not part of this view: run `make ir-report`.");
  return lines.join("\n") + "\n";
}
